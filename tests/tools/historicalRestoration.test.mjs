test('read-only Windows diagnostic probe reports its own HRESULT without claiming Node root cause', () => {
  const f = fixture(); fs.unlinkSync(f.options.targetPath);
  assert.throws(() => restoreHistoricalOutput(f.options), /ENOENT/);
  const record = JSON.parse(fs.readFileSync(f.options.diagnosticPath, 'utf8'));
  assert.equal(record.targetExists, false);
  if (process.platform === 'win32') { assert.equal(record.windows.status, 'FAIL'); assert.match(record.windows.nativeError.hresultHex, /^0x[0-9A-F]{8}$/); }
  assert.match(record.nativeErrorFromFailedOperation, /NOT AVAILABLE/);
});
