const pngOriginalSha = 'd8aeb7b31114535bbf9035568464d5eb3dadfabaa70525a487d2c04571203426';
const pngGeneratedSha = '431ced6916a2a21a156e38701afe55bbd7f88969fbbfc56d7fe099d47f265460';
const hash = (file) => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
// Fixtures are deliberately retained in the OS temporary directory for inspection.
function fixture(json = false, name = 'historical.png') {
  const root = fs.mkdtempSync(path.join(tmpdir(), 'blackjack-h1-'));
  const directory = path.join(root, "Windows paths 空格 ' [fixture]");
  fs.mkdirSync(directory);
  const original = json ? Buffer.from('{"original":true}\r\n') : originalPng;
  const generated = json ? Buffer.from('{"generated":true}\n') : generatedPng;
  const options = {
    targetPath: path.join(directory, name), backupPath: path.join(root, 'backup.bin'),
    archivePath: path.join(root, 'archive', 'generated.bin'), diagnosticPath: path.join(root, 'failure.json'),
    expectedOriginalSha256: json ? 'b394f0692c06177a3960586e9ffa8f5ba3888a720acdaf62e6461398935bc992' : pngOriginalSha,
    expectedGeneratedSha256: json ? 'b0ec07581d579e53bbad320af611ba477d29110c5238a8f4396a5e9c7382c99d' : pngGeneratedSha,
  };
  fs.writeFileSync(options.backupPath, original, { flag: 'wx' });
  fs.writeFileSync(options.targetPath, generated, { flag: 'wx' });
  return { root, options, original, generated };
}
function failure(f, overrides, message) {
  let thrown;
  assert.throws(() => { try { restoreHistoricalOutput(f.options, { ...fs, ...overrides }); } catch (error) { thrown = error; throw error; } }, message);
  assert.equal(thrown.restorationFailure.status, 'FAIL');
  assert.equal(hash(f.options.backupPath), f.options.expectedOriginalSha256);
  assert.equal(JSON.parse(fs.readFileSync(f.options.diagnosticPath, 'utf8')).status, 'FAIL');
  return thrown.restorationFailure;
}

for (const json of [false, true]) test(`normal ${json ? 'JSON' : 'PNG'} restores exact bytes, archives generated bytes, cleans temporary files`, () => {
  const f = fixture(json, json ? 'historical.json' : 'historical.png');
  const record = restoreHistoricalOutput(f.options);
  assert.equal(record.status, 'PASS'); assert.equal(record.replacementAttempts, 1);
  assert.deepEqual(fs.readFileSync(f.options.targetPath), f.original);
  assert.deepEqual(fs.readFileSync(f.options.archivePath), f.generated);
  assert.deepEqual(fs.readFileSync(f.options.backupPath), f.original);
  assert.equal(hash(f.options.targetPath), f.options.expectedOriginalSha256);
  assert.equal(hash(f.options.archivePath), f.options.expectedGeneratedSha256);
  assert.equal(fs.existsSync(record.temporaryPath), false);
  assert.equal(fs.existsSync(record.replacementPath), false);
  assert.equal(fs.existsSync(f.options.diagnosticPath), false);
});
test('archive is verified before target replacement and target is never directly written', () => {
  const f = fixture(); let calls = 0;
  restoreHistoricalOutput(f.options, { ...fs,
    writeFileSync(file, bytes, options) { assert.notEqual(file, f.options.targetPath); return fs.writeFileSync(file, bytes, options); },
    renameSync(from, to) {
      calls++;
      assert.equal(hash(f.options.archivePath), pngGeneratedSha);
      assert.equal(hash(f.options.targetPath), pngGeneratedSha);
      assert.equal(hash(from), pngOriginalSha);
      assert.equal(path.dirname(from), path.dirname(to));
      fs.renameSync(from, to);
    },
  });
  assert.equal(calls, 1);
});
