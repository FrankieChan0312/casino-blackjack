import * as fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import console from 'node:console';
import { createHash, randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { Buffer } from 'node:buffer';
import { pathToFileURL } from 'node:url';

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const requireHash = (bytes, expected, label) => {
  if (sha256(bytes) !== expected) throw new Error(`${label} SHA256 mismatch`);
};
const errorFields = (error) => ({
  errno: error.errno ?? null, code: error.code ?? null, syscall: error.syscall ?? null,
  message: error.message, stack: error.stack ?? null,
});
const inspect = (read) => {
  try { return read(); } catch (error) { return { unavailable: errorFields(error) }; }
};

// A read-only follow-up probe. Its HRESULT belongs to this probe, never to the
// earlier Node operation. Node/libuv errno is not a native Windows error code.
function windowsMetadata(targetPath) {
  if (process.platform !== 'win32') return { status: 'NOT APPLICABLE', reason: 'Windows only' };
  const command = `
$result = @{ operation = 'read-only .NET metadata/open probe'; nativeError = $null }
try {
  $result.attributes = [int][IO.File]::GetAttributes($env:H1_DIAGNOSTIC_TARGET)
  $result.attributeNames = [IO.File]::GetAttributes($env:H1_DIAGNOSTIC_TARGET).ToString()
  $stream = [IO.File]::Open($env:H1_DIAGNOSTIC_TARGET, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::ReadWrite -bor [IO.FileShare]::Delete)
  $stream.Dispose()
  $result.status = 'PASS'
} catch {
  $exception = $_.Exception.GetBaseException()
  $result.status = 'FAIL'
  $result.nativeError = @{ hresult = $exception.HResult; hresultHex = ('0x{0:X8}' -f $exception.HResult); message = $exception.Message; type = $exception.GetType().FullName }
}
$result | ConvertTo-Json -Depth 5 -Compress
`;
  const env = { ...process.env, H1_DIAGNOSTIC_TARGET: targetPath };
  for (const key of Object.keys(env)) if (key.toLowerCase() === 'psmodulepath') delete env[key];
  const shell = path.join(process.env.SystemRoot ?? 'C:\\Windows', 'System32/WindowsPowerShell/v1.0/powershell.exe');
  const probe = spawnSync(shell, ['-NoProfile', '-NonInteractive', '-EncodedCommand', Buffer.from(command, 'utf16le').toString('base64')], {
    env, encoding: 'utf8', timeout: 10000, windowsHide: true,
  });
  if (probe.error || probe.status !== 0) return { status: 'BLOCKED', exitCode: probe.status, error: probe.error?.message ?? probe.stderr };
  return inspect(() => JSON.parse(probe.stdout.replace(/^\uFEFF/, '')));
}

/** One attempt, no retries. The optional filesystem seam is only for fixtures. */
export function restoreHistoricalOutput(options, io = fs) {
  const { expectedOriginalSha256, expectedGeneratedSha256 } = options;
  const targetPath = path.resolve(options.targetPath);
  const backupPath = path.resolve(options.backupPath);
  const archivePath = path.resolve(options.archivePath);
  const diagnosticPath = path.resolve(options.diagnosticPath);
  const parentDirectory = path.dirname(targetPath);
  const id = randomUUID();
  const temporaryPath = path.join(parentDirectory, `.h1-original-${id}.tmp`);
  const replacementPath = path.join(parentDirectory, `.h1-replace-${id}.tmp`);
  let operation = 'validate paths and expected hashes';
  let sourcePath = backupPath;
  try {
    const names = [targetPath, backupPath, archivePath, diagnosticPath].map((file) => process.platform === 'win32' ? file.toLowerCase() : file);
    if (new Set(names).size !== names.length) throw new Error('Evidence paths must be distinct');
    for (const digest of [expectedOriginalSha256, expectedGeneratedSha256]) {
      if (!/^[a-f0-9]{64}$/.test(digest)) throw new Error('Explicit lowercase SHA256 is required');
    }
    for (const file of [targetPath, backupPath]) {
      if (!io.lstatSync(file).isFile()) throw new Error('Target and backup must be regular files');
    }
    operation = 'read and verify original backup';
    const original = io.readFileSync(backupPath);
    requireHash(original, expectedOriginalSha256, 'Original backup');
    operation = 'read and verify generated target'; sourcePath = targetPath;
    const generated = io.readFileSync(targetPath);
    requireHash(generated, expectedGeneratedSha256, 'Generated target');
    operation = 'archive generated bytes';
    io.mkdirSync(path.dirname(archivePath), { recursive: true });
    io.writeFileSync(archivePath, generated, { flag: 'wx', flush: true });
    operation = 'verify generated archive'; sourcePath = archivePath;
    requireHash(io.readFileSync(archivePath), expectedGeneratedSha256, 'Generated archive');
    operation = 'materialize original temporary copy'; sourcePath = backupPath;
    io.writeFileSync(temporaryPath, original, { flag: 'wx', flush: true });
    operation = 'verify original temporary copy'; sourcePath = temporaryPath;
    requireHash(io.readFileSync(temporaryPath), expectedOriginalSha256, 'Temporary original');
    // Keep the verified original copy across rename and post-rename verification.
    // Rename consumes its source, so a separate verified replacement is needed.
    operation = 'materialize replacement copy';
    io.writeFileSync(replacementPath, io.readFileSync(temporaryPath), { flag: 'wx', flush: true });
    operation = 'verify replacement copy'; sourcePath = replacementPath;
    requireHash(io.readFileSync(replacementPath), expectedOriginalSha256, 'Replacement');
    operation = 'verify target unchanged before replacement'; sourcePath = targetPath;
    requireHash(io.readFileSync(targetPath), expectedGeneratedSha256, 'Target before replacement');
    operation = 'replace target once'; sourcePath = replacementPath;
    io.renameSync(replacementPath, targetPath);
    operation = 'verify restored target'; sourcePath = targetPath;
    requireHash(io.readFileSync(targetPath), expectedOriginalSha256, 'Restored target');
    operation = 'verify retained backup and archive';
    requireHash(io.readFileSync(backupPath), expectedOriginalSha256, 'Retained backup');
    requireHash(io.readFileSync(archivePath), expectedGeneratedSha256, 'Retained archive');
    operation = 'remove temporary copy after success'; sourcePath = temporaryPath;
    io.unlinkSync(temporaryPath);
    return { status: 'PASS', targetPath, backupPath, archivePath, originalSha256: expectedOriginalSha256,
      generatedSha256: expectedGeneratedSha256, replacementAttempts: 1, temporaryPath, replacementPath };
  } catch (error) {
    const record = {
      at: new Date().toISOString(), status: 'FAIL', nodeVersion: process.version, processId: process.pid,
      operation, sourcePath, targetPath, backupPath, archivePath, temporaryPath, replacementPath,
      parentDirectory, ...errorFields(error),
      targetExists: inspect(() => fs.existsSync(targetPath)),
      targetMetadata: inspect(() => { const stat = fs.statSync(targetPath); return { size: stat.size, mode: stat.mode, modifiedAt: stat.mtime.toISOString() }; }),
      backupSha256: inspect(() => sha256(fs.readFileSync(backupPath))),
      currentTargetSha256: inspect(() => sha256(fs.readFileSync(targetPath))),
      windows: windowsMetadata(targetPath),
      nativeErrorFromFailedOperation: 'NOT AVAILABLE: Node did not expose a native Windows error/HRESULT',
    };
    try {
      // No overwrite and no failure cleanup; diagnostics cannot damage evidence.
      fs.mkdirSync(path.dirname(diagnosticPath), { recursive: true });
      fs.writeFileSync(diagnosticPath, JSON.stringify(record, null, 2) + '\n', { flag: 'wx' });
    } catch (diagnosticError) { record.diagnosticWriteError = errorFields(diagnosticError); }
    error.restorationFailure = record;
    throw error;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    if (process.argv.length !== 3) throw new Error('Usage: node scripts/restore-historical-output.mjs <plan.json>');
    const plan = JSON.parse(fs.readFileSync(process.argv[2], 'utf8').replace(/^\uFEFF/, ''));
    console.log(JSON.stringify(restoreHistoricalOutput(plan)));
  } catch (error) {
    console.error(JSON.stringify(error.restorationFailure ?? errorFields(error), null, 2));
    process.exitCode = 1;
  }
}
